    private void btnGenerateOrderActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGenerateOrderActionPerformed
        String customerName = txtCustomerName.getText().trim();

if (customerName.isEmpty()) {
    JOptionPane.showMessageDialog(this, "Please enter the customer's name.");
    txtCustomerName.requestFocus();
    return;
}

String meal = (String) cmbMeal.getSelectedItem();

String mealSize = "";
if (rdoSmall.isSelected()) {
    mealSize = "Small";
} else if (rdoRegular.isSelected()) {
    mealSize = "Regular";
} else if (rdoLarge.isSelected()) {
    mealSize = "Large";
}

String orderType;
if (chkTakeaway.isSelected()) {
    orderType = "Takeaway";
} else {
    orderType = "Dine In";
}

String summary = "========== CAMPUS CAFE ==========\n\n"
        + "Customer: " + customerName + "\n"
        + "Meal: " + meal + "\n"
        + "Meal Size: " + mealSize + "\n"
        + "Order Type: " + orderType + "\n\n"
        + "Thank you for your order!\n"
        + "=================================\n";

txtOrderSummary.setText(summary);
    }//GEN-LAST:event_btnGenerateOrderActionPerformed

